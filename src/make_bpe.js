// Trains Echo's tokenizer once, at build time, and writes the merges into bpe_data.js
const fs = require('fs');
eval(fs.readFileSync(__dirname + '/library.js', 'utf8') + ';global.LIBRARY=LIBRARY;');
const { Nest } = require('./engine.js');
const extra = fs.readFileSync(__dirname + '/common_words.txt', 'utf8').trim().split(/\s+/);
/* the poisoned book and Pebble's private diary are kept apart from the tokenizer too */
const lib = LIBRARY.filter(b => b.kind !== 'poison' && b.kind !== 'diary').map(b => b.text).join('\n');
const libWords = Array.from(new Set((lib.match(/[A-Za-z]+/g) || [])));
const corpus = [lib, lib,
  extra.join(' '), extra.join('\n'),
  extra.map(w => w.charAt(0).toUpperCase() + w.slice(1)).join('\n'),
  libWords.map(w => w.toLowerCase()).join('\n'), libWords.join('\n')].join('\n');
const t0 = Date.now();
const merges = Nest.BPE.train(corpus, +(process.argv[2] || 1500));
fs.writeFileSync(__dirname + '/bpe_data.js', '/* Echo\'s tokenizer: ' + merges.length + ' merges learned from the library and a list of common words (generated by make_bpe.js) */\nconst BPE_MERGES = ' + JSON.stringify(merges) + ';\n');
console.log('merges', merges.length, 'ms', Date.now() - t0);
