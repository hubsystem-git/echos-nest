MANIFEST = {
    'name': "Echo's Nest",
    'short_name': "Echo's Nest",
    'description': "How AI and chatbots really work, learned by teaching a baby raven to talk.",
    'lang': 'en',
    'start_url': './',
    'scope': './',
    'display': 'standalone',
    'background_color': BRAND,
    'theme_color': BRAND,
    'icons': [
        {'src': 'icons/icon-192.png', 'sizes': '192x192', 'type': 'image/png'},
        {'src': 'icons/icon-512.png', 'sizes': '512x512', 'type': 'image/png'},
        {'src': 'icons/icon-maskable-512.png', 'sizes': '512x512', 'type': 'image/png', 'purpose': 'maskable'},
    ],
}

# What the service worker keeps for offline use. The page itself is always fetched fresh when there is a connection.
OFFLINE = ['./', 'index.html', 'manifest.webmanifest', 'icons/icon-192.png', 'icons/icon-512.png', 'icons/apple-touch-icon.png']
SW = '''/* Echo's Nest service worker: lets the guide open without a connection after the first visit.
   Generated by src/build.py. */
const CACHE = 'echos-nest-%(version)s';
const FILES = %(files)s;
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('echos-nest-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
/* The page: try the network first, so updates arrive, but don't wait more than a few seconds before using the saved copy. */
function page(req) {
  const net = fetch(req).then(res => {
    if (res && res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put('index.html', copy)); }
    return res;
  });
  const saved = new Promise(resolve => setTimeout(resolve, 4000)).then(() => caches.match('index.html'));
  return Promise.race([net.catch(() => caches.match('index.html')), saved.then(r => r || net)]);
}
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') { e.respondWith(page(req)); return; }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req)));
});
'''


def read(name):
    with open(os.path.join(HERE, name), encoding='utf-8') as f:
        return f.read()


def script_js():
    js = '\n'.join(read(f).replace("if (typeof module !== 'undefined') module.exports = { Nest: Nest };", '')
                   .replace("if (typeof module !== 'undefined') module.exports = { Widgets: Widgets };", '') for f in JS_FILES)
    assert '</script' not in js.lower(), 'a closing script tag inside the JS would end the script early'
    assert '<!--' not in js, 'an HTML comment opener inside the JS'
    # check the whole bundle parses before it ships
    with tempfile.NamedTemporaryFile('w', suffix='.js', delete=False, encoding='utf-8') as t:
        t.write(js)
    try:
        subprocess.run(['node', '--check', t.name], check=True)
    finally:
        os.remove(t.name)
    return js


def font_faces():
    out = []
    for f in json.load(open(os.path.join(HERE, 'fonts', 'fonts.json'), encoding='utf-8')):
        data = base64.b64encode(open(os.path.join(HERE, 'fonts', f['file']), 'rb').read()).decode('ascii')
        out.append('@font-face{font-family:"%s";font-style:%s;font-weight:%d;font-display:swap;'
                   'src:url(data:font/woff2;base64,%s) format("woff2");unicode-range:%s;}'
                   % (f['family'], f['style'], f['weight'], data, f['unicodeRange']))
    return '\n'.join(out)


def build():
    subprocess.run(['node', os.path.join(HERE, 'make_bpe.js'), '1500'], check=True)
    js = script_js()
    head = HEAD.format(title=TITLE, desc=DESC, light=LIGHT_BG, dark=DARK_BG)
    page = ('<!doctype html>\n<html lang="en">\n<head>\n%s\n'
            '<style>\n/* Fonts (SIL Open Font License 1.1, see the licenses folder) */\n%s\n%s\n</style>\n</head>\n<body>\n%s'
            '<script>\n%s\n</script>\n</body>\n</html>\n') % (head, font_faces(), read('style.css'), BODY, js)
    assert 'googleapis' not in page and 'gstatic' not in page
    open(os.path.join(ROOT, 'index.html'), 'w', encoding='utf-8').write(page)
    open(os.path.join(ROOT, 'manifest.webmanifest'), 'w', encoding='utf-8').write(json.dumps(MANIFEST, indent=2) + '\n')
    version = hashlib.sha256(page.encode('utf-8')).hexdigest()[:12]
    open(os.path.join(ROOT, 'sw.js'), 'w', encoding='utf-8').write(SW % {'version': version, 'files': json.dumps(OFFLINE)})
    lic = os.path.join(ROOT, 'licenses')
    os.makedirs(lic, exist_ok=True)
    for name in os.listdir(os.path.join(HERE, 'fonts', 'licenses')):
        shutil.copyfile(os.path.join(HERE, 'fonts', 'licenses', name), os.path.join(lic, name))
    open(os.path.join(ROOT, '.nojekyll'), 'w').close()
    print('index.html', len(page.encode()), 'bytes; version', version)


if __name__ == '__main__':
    build()
