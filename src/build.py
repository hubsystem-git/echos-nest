"""Build Echo's Nest as a web app for GitHub Pages.

  python3 src/build.py

Writes, at the top of the repository:
  index.html            the whole guide in one page (scripts, styles and fonts inside)
  sw.js                 the service worker that lets it open offline after the first visit
  manifest.webmanifest  what iPhone, iPad and other devices need to install it as an app
  licenses/             the font licenses
Needs Python 3 and Node.js. Icons are made separately by make_icons.py.
"""
