/* Echo's Nest service worker. After the first visit the guide opens straight away, with or without a connection.
   Generated by src/build.py. */
const CACHE = 'echos-nest-ba9cd7d01bc7';
const FILES = ["index.html", "manifest.webmanifest", "icons/icon-192.png", "icons/icon-512.png", "icons/apple-touch-icon.png"];
const MARK = 'name="echos-nest"';
self.addEventListener('install', e => {
  /* cache: 'reload' skips the browser's own cache, so a new version never saves an old copy */
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES.map(u => new Request(u, { cache: 'reload' })))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('echos-nest-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
/* the newest copy of the page, but only if it really is the guide */
function fresh() {
  return fetch(new Request('index.html', { cache: 'no-cache' }))
    .then(res => res && res.ok && res.type === 'basic' ? res.clone().text().then(t => t.indexOf(MARK) >= 0 ? res : null) : null)
    .catch(() => null);
}
const SCOPE = new URL(self.registration.scope).pathname;
const isPage = url => url.pathname === SCOPE || url.pathname === SCOPE + 'index.html';
self.addEventListener('fetch', e => {
  const req = e.request, url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    if (!isPage(url)) return;
    /* the saved copy opens straight away; a newer one, if there is one, is saved for next time */
    const net = fresh().then(res => res ? caches.open(CACHE).then(c => c.put('index.html', res.clone())).then(() => res) : null);
    e.waitUntil(net);
    e.respondWith(caches.match('index.html').then(hit => hit || net.then(res => res || fetch(req))));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req)));
});
