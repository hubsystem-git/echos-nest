/* Echo's Nest service worker: lets the guide open without a connection after the first visit.
   Generated by src/build.py. */
const CACHE = 'echos-nest-650f0b0c374f';
const FILES = ["./", "index.html", "manifest.webmanifest", "icons/icon-192.png", "icons/icon-512.png", "icons/apple-touch-icon.png"];
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('echos-nest-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
/* The page: try the network first, so updates arrive, but don't wait more than a few seconds before using the saved copy. */
function page(req) {
  const net = fetch(req).then(res => {
    if (res && res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put('index.html', copy)); }
    return res;
  });
  const saved = new Promise(resolve => setTimeout(resolve, 4000)).then(() => caches.match('index.html'));
  return Promise.race([net.catch(() => caches.match('index.html')), saved.then(r => r || net)]);
}
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') { e.respondWith(page(req)); return; }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req)));
});
